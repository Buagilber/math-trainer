// Множення стовпчиком з неповними добутками («Розписати множення»).
//
// longMultiplication(47, 23) повертає поля в тому порядку, у якому множать на папері:
//   pp  — неповний добуток: перший множник × цифра другого (від одиниць);
//         shift — на скільки розрядів зсунутий ліворуч (нулі в кінці не пишуть);
//   sum — сума неповних добутків (відповідь).
// Цифра 0 у другому множнику рядка не дає: наступний добуток зсувається далі
// (47 · 205 → 235, далі 94 зі зсувом на 2).
//
// 47 · 23 → pp 141 (зсув 0) · pp 94 (зсув 1) · sum 1081.
// width — скільки колонок займає рядок: на цифру більше за перший множник
// (неповний добуток може бути на цифру довшим), щоб поле не підказувало
// довжину відповіді.

export function longMultiplication(a, b) {
  const total = String(a * b).length;
  const fields = String(b).split('').reverse().flatMap((d, shift) => (d === '0' ? [] : [{
    kind: 'pp',
    value: a * Number(d),
    shift,
    width: Math.min(String(a).length + 1, total - shift),
  }]));
  fields.push({ kind: 'sum', value: a * b, shift: 0, width: total });
  return fields;
}
